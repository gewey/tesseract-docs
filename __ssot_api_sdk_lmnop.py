def _esc(value):
    return html.escape(str(value if value is not None else ""), quote=True)


def _chip_list(names, limit=None):
    if not names:
        return "<p class=\"noContent\">None.</p>"
    shown = names if limit is None else names[:limit]
    chips = "".join(f"<code>{_esc(n)}</code> " for n in shown)
    if limit is not None and len(names) > limit:
        chips += f"<em>+{len(names) - limit} more</em>"
    return f"<p class=\"code-inline-wrap\">{chips}</p>"


def _stage_nav_button(target, label, badge, badge_class="get", active=False):
    cls = "endpoint-btn active" if active else "endpoint-btn"
    return (f"<div class=\"{cls}\" onclick=\"loadDoc('{_esc(target)}')\">"
            f"<span class=\"method-badge {badge_class}\">{_esc(badge)}</span>"
            f"<span>{_esc(label)}</span></div>")


def _overview_stage(manifest):
    counts = manifest.get("counts") or {}
    hubs = manifest.get("hubs") or {}
    loaded = sum(1 for v in hubs.values() if v)
    collisions = manifest.get("collisions") or []

    parts = [
        "<div id=\"overview\" class=\"doc-stage active\">",
        "<div class=\"endpoint-header\">"
        "<span class=\"method-badge get\">LIVE</span>"
        "<span class=\"endpoint-path\">from _TERMINUS import *</span></div>",
        "<p style=\"color:#DDD;line-height:1.6;\">Every shelf of Terminus contributes names "
        "to one flat surface. This page is that surface, measured from the running substrate: "
        "static facts come from parsing each numbered shelf, live facts from a child process "
        "that imported <code>_TERMINUS</code>. Add a shelf and it appears here; remove one and "
        "every other section is unchanged.</p>",
        "<h3 style=\"color:var(--color-primary,#00EA00);font-size:1em;\">Reaching it</h3>",
        "<pre><code>from _TERMINUS import *            # the whole surface\n"
        "from _TERMINUS import get_module   # reach any script by name\n"
        "thing = get_module('my_script')" + "</code></pre>",
        "<h3 style=\"color:var(--color-accent,#EE00EE);font-size:1em;\">Surface</h3>",
        "<table class=\"param-table\"><thead><tr><th>Measure</th><th>Value</th></tr></thead><tbody>",
        f"<tr><td>Exported names</td><td><code>{counts.get('total', 0)}</code></td></tr>",
        f"<tr><td>Callable</td><td><code>{counts.get('callable', 0)}</code></td></tr>",
        f"<tr><td>Classes</td><td><code>{counts.get('class', 0)}</code></td></tr>",
        f"<tr><td>Modules</td><td><code>{counts.get('module', 0)}</code></td></tr>",
        f"<tr><td>Plain values</td><td><code>{counts.get('value', 0)}</code></td></tr>",
        f"<tr><td>Unbound names</td><td><code>{counts.get('none', 0) + counts.get('missing', 0)}</code></td></tr>",
        f"<tr><td>Hubs loaded</td><td><code>{loaded}/{len(hubs)}</code></td></tr>",
        "</tbody></table>",
    ]
    if collisions:
        parts += ["<h3 style=\"color:var(--color-accent,#EE00EE);font-size:1em;\">"
                  "Names shared by hubs</h3>",
                  "<p style=\"color:#DDD;\">A few names are exported by more than one sibling "
                  "hub. The binding you receive is the hub that sorts first.</p>",
                  "<table class=\"param-table\"><thead><tr><th>Name</th><th>Hubs</th>"
                  "<th>Binding</th></tr></thead><tbody>"]
        for c in collisions:
            parts.append(f"<tr><td><code>{_esc(c['name'])}</code></td>"
                         f"<td>{_esc(', '.join(c['hubs']))}</td>"
                         f"<td><code>{_esc(c['winner'])}</code></td></tr>")
        parts.append("</tbody></table>")
    parts.append("</div>")
    return "\n".join(parts)


def _exports_by_shelf(manifest):
    shelf_of_module = {}
    for shelf_name, shelf in (manifest.get("shelves") or {}).items():
        for module in shelf.get("modules") or []:
            shelf_of_module[module["file"][:-3]] = shelf_name
    found = {}
    for record in manifest.get("exported") or []:
        for owner in record.get("owners") or []:
            if owner.get("kind") != "ssot":
                continue
            shelf_name = shelf_of_module.get(owner.get("module"))
            if shelf_name:
                found.setdefault(shelf_name, set()).add(record["name"])
    return {k: sorted(v) for k, v in found.items()}


def _shelf_stage(name, shelf, live_names):
    status = shelf.get("status", "unknown")
    badge = {"ok": "get", "partial": "post", "empty": "post"}.get(status, "post")
    parts = [f"<div id=\"shelf-{_esc(name)}\" class=\"doc-stage\">",
             "<div class=\"endpoint-header\">"
             f"<span class=\"method-badge {badge}\">{_esc(status.upper())}</span>"
             f"<span class=\"endpoint-path\">{_esc(name)}</span></div>"]
    if shelf.get("error"):
        parts.append(f"<p style=\"color:#c66;\">{_esc(shelf['error'])}</p>")
    modules = shelf.get("modules") or []
    if not modules:
        parts.append("<p style=\"color:#DDD;\">No <code>__ssot_*.py</code> on this shelf. "
                     "That is allowed — a shelf can be support files only.</p>")
    else:
        parts += ["<table class=\"param-table\"><thead><tr><th>Module</th><th>Version</th>"
                  "<th>Lines</th><th>Functions</th><th>Classes</th><th>Contract</th>"
                  "</tr></thead><tbody>"]
        for module in modules:
            if module.get("status") != "ok":
                parts.append(f"<tr><td><code>{_esc(module['file'])}</code></td>"
                             f"<td colspan=\"5\">{_esc(module.get('error'))}</td></tr>")
                continue
            parts.append(
                f"<tr><td><code>{_esc(module['file'])}</code><br>"
                f"<small style=\"color:#999;\">{_esc(module.get('doc') or '')}</small></td>"
                f"<td><code>{_esc(module.get('version') or '—')}</code></td>"
                f"<td><code>{module.get('lines', 0)}</code></td>"
                f"<td><code>{len(module.get('functions') or [])}</code></td>"
                f"<td><code>{len(module.get('classes') or [])}</code></td>"
                f"<td>{'yes' if module.get('has_contract') else '—'}</td></tr>"
            )
        parts.append("</tbody></table>")
    if live_names:
        parts += ["<h3 style=\"color:var(--color-primary,#00EA00);font-size:1em;\">"
                  "Live through _TERMINUS</h3>", _chip_list(live_names)]
    parts.append("</div>")
    return "\n".join(parts)


def _tombstone_stage(name, manifest):
    return ("<div id=\"shelf-" + _esc(name) + "\" class=\"doc-stage\">"
            "<div class=\"endpoint-header\">"
            "<span class=\"method-badge post\">ABSENT</span>"
            f"<span class=\"endpoint-path\">{_esc(name)}</span></div>"
            "<p style=\"color:#DDD;\">This shelf existed on a previous run and is gone now. "
            "Its page was replaced with this tombstone. Every other shelf still generated — "
            "that is the modularity contract.</p></div>")


def _hub_stage(hub_name, loaded, names):
    parts = [f"<div id=\"hub-{_esc(hub_name)}\" class=\"doc-stage\">",
             "<div class=\"endpoint-header\">"
             f"<span class=\"method-badge {'get' if loaded else 'post'}\">"
             f"{'LOADED' if loaded else 'FAILED'}</span>"
             f"<span class=\"endpoint-path\">{_esc(hub_name)}</span></div>"]
    if not loaded:
        parts.append("<p style=\"color:#DDD;\">The OMEGA hub caught this hub's import error "
                     "and stored <code>None</code>. Fail-soft: the rest of the surface "
                     "still works.</p>")
    else:
        parts.append(_chip_list(names))
    parts.append("</div>")
    return "\n".join(parts)


def _render_page(manifest, summary):
    shelves = manifest.get("shelves") or {}
    absent = manifest.get("absent_shelves") or []
    hubs = manifest.get("hubs") or {}
    hub_exports = manifest.get("hub_exports") or {}
    by_shelf = _exports_by_shelf(manifest)

    nav = [_stage_nav_button("overview", "Runtime surface", "Σ", active=True)]
    if absent:
        for name in absent:
            nav.append(_stage_nav_button(f"shelf-{name}", name, "∅", "post"))
    nav.append("<div class=\"doc-nav-section\">Shelves</div>")
    for name in sorted(shelves):
        nav.append(_stage_nav_button(f"shelf-{name}", name, str(len(shelves[name].get('modules') or []))))
    if hubs:
        nav.append("<div class=\"doc-nav-section\">Hubs</div>")
        for hub_name in sorted(hubs):
            nav.append(_stage_nav_button(f"hub-{hub_name}", hub_name,
                                         "!" if not hubs[hub_name] else "H", 
                                         "post" if not hubs[hub_name] else "get"))

    stages = [_overview_stage(manifest)]
    for name in absent:
        stages.append(_tombstone_stage(name, manifest))
    for name in sorted(shelves):
        stages.append(_shelf_stage(name, shelves[name], by_shelf.get(name, [])))
    for hub_name in sorted(hubs):
        stages.append(_hub_stage(hub_name, hubs[hub_name], hub_exports.get(hub_name, [])))

    generated = manifest.get("generated", summary.get("generated", ""))
    version = manifest.get("terminus_version") or "unknown"
    return "\n".join([
        "<!DOCTYPE html>",
        "<html lang=\"en\">",
        "<head>",
        _HEAD_LOADER,
        "</head>",
        "<body>",
        "<div class=\"viewArea\">",
        "<div class=\"pageHeader\">",
        f"<marquee>⚙️ TESSERACT CITY — API · SDK · LMNOP — Terminus {_esc(version)} "
        f"— generated {_esc(generated)}</marquee>",
        "</div>",
        "<div class=\"mainArea\">",
        "<div class=\"pageLeftMenu\">",
        "<div class=\"doc-nav-section\">Reference</div>",
        *nav,
        "</div>",
        "<div class=\"pageContent\">",
        *stages,
        "</div>",
        "</div>",
        "<div class=\"pageFooter\">",
        "<span>Generated from the running substrate. "
        "<a href=\"index.html\">Docs home</a> · <a href=\"../../index.html\">Homepage</a></span>",
        "</div>",
        "</div>",
        "<script>" + _LOAD_DOC_JS + "</script>",
        "</body>",
        "</html>",
        "",
    ])


_LOAD_DOC_JS = """
function loadDoc(docId) {
    document.querySelectorAll('.doc-stage').forEach(s => s.classList.remove('active'));
    document.querySelectorAll('.endpoint-btn').forEach(b => b.classList.remove('active'));
    const target = document.getElementById(docId);
    if (target) target.classList.add('active');
    if (event && event.currentTarget) event.currentTarget.classList.add('active');
}
"""


