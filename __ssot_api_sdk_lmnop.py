if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Publish the API/SDK/LMNOP reference.")
    parser.add_argument("--out", default=None, help="docs directory (default: this folder)")
    parser.add_argument("--no-live", action="store_true", help="skip the _TERMINUS subprocess")
    parser.add_argument("--status", action="store_true", help="print status and exit")
    args = parser.parse_args()

    if args.status:
        print(json.dumps(get_api_sdk_lmnop_status(), indent=2))
