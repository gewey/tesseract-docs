def _find_terminus():
    here = Path(__file__).resolve().parent
    for candidate in [here, *here.parents]:
        target = candidate / "__terminus__"
        if target.is_dir():
            return target
    return None


def _load_aoit_tool():
    terminus = _find_terminus()
    if terminus is None:
        raise RuntimeError("marinus: __terminus__ not found from " + str(DOCS_DIR))
    tool = terminus / "06_Documentation" / "__ssot_aoit.py"
    if not tool.is_file():
        raise RuntimeError("marinus: AOIT tool missing at " + str(tool))
    spec = importlib.util.spec_from_file_location("aoit_tool", tool)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


